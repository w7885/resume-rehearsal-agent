CREATE FUNCTION app_same_owner() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE conflict_found boolean;
BEGIN
  EXECUTE format('SELECT EXISTS (SELECT 1 FROM %I WHERE %I = $1 AND session_id <> $2)', TG_TABLE_NAME, TG_ARGV[0])
    INTO conflict_found USING to_jsonb(NEW)->>TG_ARGV[0], NEW.session_id;
  IF conflict_found THEN
    RAISE EXCEPTION 'Snapshot identity belongs to another session' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER sources_same_owner BEFORE INSERT ON source_blocks
  FOR EACH ROW EXECUTE FUNCTION app_same_owner('source_id');
CREATE TRIGGER draft_same_owner BEFORE INSERT ON draft_blocks
  FOR EACH ROW EXECUTE FUNCTION app_same_owner('block_id');
CREATE FUNCTION app_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Snapshots are immutable; create a new revision' USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER sources_immutable BEFORE UPDATE OF source_id, source_revision, session_id, attachment_id, message_id, role, text, origin_json, page_number, line_start, line_end ON source_blocks
  FOR EACH ROW EXECUTE FUNCTION app_immutable();
CREATE TRIGGER draft_snapshots_immutable BEFORE UPDATE OF block_id, block_revision, session_id, markdown ON draft_blocks
  FOR EACH ROW EXECUTE FUNCTION app_immutable();
CREATE TRIGGER external_references_immutable BEFORE UPDATE ON external_references
  FOR EACH ROW EXECUTE FUNCTION app_immutable();
CREATE TRIGGER external_assessments_immutable BEFORE UPDATE ON external_assessments
  FOR EACH ROW EXECUTE FUNCTION app_immutable();
CREATE FUNCTION app_scrub_requests() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE request_log SET state='deleted', request_hash=NULL, response_json=NULL, session_id=NULL
    WHERE session_id=OLD.session_id;
  RETURN OLD;
END;
$$;
CREATE TRIGGER scrub_deleted_session_requests BEFORE DELETE ON sessions
  FOR EACH ROW EXECUTE FUNCTION app_scrub_requests();
