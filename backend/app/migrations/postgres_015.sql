CREATE FUNCTION app_json_valid(value text) RETURNS boolean LANGUAGE plpgsql IMMUTABLE STRICT AS $$
BEGIN
  PERFORM value::json;
  RETURN true;
EXCEPTION WHEN invalid_text_representation THEN RETURN false;
END;
$$;
CREATE FUNCTION app_json_type(value text) RETURNS text LANGUAGE plpgsql IMMUTABLE STRICT AS $$
BEGIN
  RETURN json_typeof(value::json);
EXCEPTION WHEN invalid_text_representation THEN RETURN NULL;
END;
$$;

